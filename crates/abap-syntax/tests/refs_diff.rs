//! Differential test of the data references of statements: which variables
//! are read and written at which position, against the references of
//! abaplint's syntax check. Only files of objects without syntax errors are
//! compared, references from macro expansions are left out.
//!
//! Two conventions of abaplint are translated before comparing:
//! - in a target like `lo->attr = x` abaplint writes `lo` and reads `attr`,
//!   we read `lo` and write `attr`;
//! - a changed operand like the table of `APPEND ... TO itab` is only
//!   written for abaplint, we read and write it;
//! - a static attribute written as `zcl=>attr = x` is read for abaplint.
//!
//! Needs golden data generated by the oracle, otherwise the test is skipped:
//!
//!   node tools/oracle.mjs tests/corpus/golden --list tests/corpus/corpora.txt
//!
//! Run with `cargo test --release -p abap-syntax --test refs_diff -- --nocapture`;
//! `REFS_KIND=Move` prints the differences of one statement kind.

mod common;

use std::collections::{BTreeMap, HashMap};

use abap_syntax::expr::Access;
use serde::Deserialize;

/// Baselines in percent; raise when improving.
const MIN_RECALL: f64 = 99.8;
const MIN_PRECISION: f64 = 94.5;

#[derive(Deserialize)]
struct Golden {
    file: String,
    #[serde(rename = "syntaxOk")]
    syntax_ok: bool,
    refs: Vec<(u32, u32, String)>,
}

#[derive(Default)]
struct Count {
    expected: usize,
    found: usize,
    ours: usize,
    correct: usize,
    missing: Vec<String>,
    extra: Vec<String>,
}

#[test]
fn refs_diff() {
    let root = common::repo_root();
    let files = common::json_files(&root.join("tests/corpus/golden/tests"));
    if files.is_empty() {
        println!("skipped: no golden data, see the comment at the top of this file");
        return;
    }
    let only = std::env::var("REFS_KIND").ok();
    let mut by_kind: BTreeMap<String, Count> = BTreeMap::new();
    let mut compared = 0;

    for f in &files {
        let golden: Golden = serde_json::from_str(&std::fs::read_to_string(f).unwrap()).unwrap();
        if !golden.syntax_ok {
            continue;
        }
        compared += 1;
        let path = root.join(&golden.file);
        let source = std::fs::read_to_string(&path).unwrap();
        let file = abap_syntax::parse_with_macros(&source, &common::sibling_macros(&path));
        let tokens = file.tokens();

        // position -> (read, write) for abaplint and for us
        let mut theirs: HashMap<(u32, u32), (bool, bool)> = HashMap::new();
        for (row, col, rw) in &golden.refs {
            let e = theirs.entry((*row, *col)).or_default();
            if rw == "R" {
                e.0 = true;
            } else {
                e.1 = true;
            }
        }
        // statement of every position, for the report
        let mut kind_at: HashMap<(u32, u32), (String, usize)> = HashMap::new();
        // (read, written, read if abaplint reads too)
        let mut ours: HashMap<(u32, u32), (bool, bool, bool)> = HashMap::new();
        for (i, s) in file.statements.iter().enumerate() {
            let real = s.tokens.iter().any(|t| !tokens[*t].expanded);
            if !real {
                continue;
            }
            for t in &s.tokens {
                let t = &tokens[*t];
                kind_at.insert((t.start.row, t.start.col), (s.kind.as_str().to_string(), i));
            }
            let refs = abap_syntax::operands::operands(&file, s).refs();
            let mut access: Vec<Access> = refs.iter().map(|r| r.access).collect();
            for (i, r) in refs.iter().enumerate() {
                if r.attribute && r.access != Access::Read {
                    let head = refs[..i]
                        .iter()
                        .position(|q| q.last == r.last && q.access == Access::Read && !q.attribute);
                    if let Some(j) = head {
                        access[j] = Access::Write;
                    }
                    // a static attribute `zcl=>attr` is only read for abaplint
                    access[i] = Access::Read;
                }
            }
            for (r, access) in refs.iter().zip(access) {
                let t = &tokens[s.tokens[r.pos]];
                if t.expanded {
                    continue;
                }
                let e = ours.entry((t.start.row, t.start.col)).or_default();
                match access {
                    Access::Read => e.0 = true,
                    Access::Write => e.1 = true,
                    Access::Change => {
                        e.1 = true;
                        e.2 = true;
                    }
                }
            }
        }

        let describe = |pos: &(u32, u32), what: &str| {
            let (_, i) = &kind_at[pos];
            let s = &file.statements[*i];
            format!(
                "{}:{}:{} {what} | {}",
                golden.file,
                pos.0,
                pos.1,
                file.statement_text(s)
            )
        };
        for (pos, (r, w)) in &theirs {
            let Some((kind, _)) = kind_at.get(pos) else {
                continue;
            };
            let c = by_kind.entry(kind.clone()).or_default();
            let mine = ours.get(pos).copied().unwrap_or_default();
            for (want, have, label) in [(*r, mine.0 || mine.2, "R"), (*w, mine.1, "W")] {
                if want {
                    c.expected += 1;
                    if have {
                        c.found += 1;
                    } else if only.as_deref() == Some(kind.as_str()) || c.missing.len() < 3 {
                        c.missing.push(describe(pos, &format!("missing {label}")));
                    }
                }
            }
        }
        for (pos, (r, w, maybe_r)) in &ours {
            let kind = kind_at.get(pos).map(|k| k.0.clone()).unwrap_or_default();
            let c = by_kind.entry(kind.clone()).or_default();
            let want = theirs.get(pos).copied().unwrap_or_default();
            let r = &(*r || (*maybe_r && want.0));
            for (have, expected, label) in [(*r, want.0, "R"), (*w, want.1, "W")] {
                if have {
                    c.ours += 1;
                    if expected {
                        c.correct += 1;
                    } else if only.as_deref() == Some(kind.as_str()) || c.extra.len() < 3 {
                        c.extra.push(describe(pos, &format!("extra {label}")));
                    }
                }
            }
        }
    }

    let total = |f: fn(&Count) -> usize| by_kind.values().map(f).sum::<usize>();
    let (expected, found, ours, correct) = (
        total(|c| c.expected),
        total(|c| c.found),
        total(|c| c.ours),
        total(|c| c.correct),
    );
    let mut kinds: Vec<_> = by_kind.iter().collect();
    // the kinds with the most differences first
    kinds.sort_by_key(|(_, c)| std::cmp::Reverse(c.expected - c.found + c.ours - c.correct));
    for (kind, c) in kinds.iter().take(25) {
        let diff = c.expected - c.found + c.ours - c.correct;
        if diff == 0 {
            continue;
        }
        println!(
            "{kind}: recall {}/{} precision {}/{}",
            c.found, c.expected, c.correct, c.ours
        );
        let n = if only.as_deref() == Some(kind.as_str()) {
            60
        } else {
            3
        };
        for m in c.missing.iter().chain(&c.extra).take(n) {
            println!("    {m}");
        }
    }
    let recall = common::percent(found, expected);
    let precision = common::percent(correct, ours);
    println!(
        "files {compared}, references {expected}: recall {recall:.2}%, precision {precision:.2}%"
    );
    assert!(recall >= MIN_RECALL, "recall {recall:.2}% < {MIN_RECALL}%");
    assert!(
        precision >= MIN_PRECISION,
        "precision {precision:.2}% < {MIN_PRECISION}%"
    );
}
